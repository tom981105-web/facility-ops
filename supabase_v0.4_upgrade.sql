-- 4) 권한 판정 함수. SECURITY DEFINER로 profiles RLS 재귀를 피합니다.
create or replace function public.facility_ops_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  );
$$;

create or replace function public.facility_ops_can_edit()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role in ('admin','member')
  );
$$;

grant execute on function public.facility_ops_is_admin() to authenticated;
grant execute on function public.facility_ops_can_edit() to authenticated;

-- 5) 로그인 시 최근 접속 시각 갱신
create or replace function public.facility_ops_touch_my_profile()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception '로그인이 필요합니다.';
  end if;

  update public.profiles
  set last_seen = now(), updated_at = now()
  where id = auth.uid();
end;
$$;

grant execute on function public.facility_ops_touch_my_profile() to authenticated;

-- 6) 관리자 사용자 목록: auth.users의 이메일은 직원에게 노출하지 않고 아이디 부분만 반환
create or replace function public.facility_ops_admin_list_users()
returns table (
  id uuid,
  login_id text,
  display_name text,
  role text,
  last_seen timestamptz,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자만 사용자 목록을 볼 수 있습니다.' using errcode = '42501';
  end if;

  return query
  select
    u.id,
    split_part(coalesce(u.email,''), '@', 1) as login_id,
    coalesce(p.display_name, split_part(coalesce(u.email,''), '@', 1)) as display_name,
    coalesce(p.role, 'member') as role,
    p.last_seen,
    u.created_at
  from auth.users u
  left join public.profiles p on p.id = u.id
  order by coalesce(p.display_name, split_part(coalesce(u.email,''), '@', 1));
end;
$$;

grant execute on function public.facility_ops_admin_list_users() to authenticated;

-- 7) 관리자 사용자 이름/권한 변경
create or replace function public.facility_ops_admin_update_profile(
  p_user_id uuid,
  p_display_name text,
  p_role text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_name text;
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자만 사용자 권한을 변경할 수 있습니다.' using errcode = '42501';
  end if;

  if p_role not in ('admin','member','viewer') then
    raise exception '올바르지 않은 권한입니다.';
  end if;

  -- 실수로 자기 관리자 권한을 없애서 시스템에서 잠기는 것을 방지
  if p_user_id = auth.uid() and p_role <> 'admin' then
    raise exception '현재 로그인한 관리자 자신의 관리자 권한은 해제할 수 없습니다.';
  end if;

  update public.profiles
  set display_name = nullif(trim(p_display_name), ''),
      role = p_role,
      updated_at = now()
  where id = p_user_id;

  select coalesce(display_name, '관리자') into v_actor_name
  from public.profiles where id = auth.uid();

  insert into public.audit_logs(table_name, record_id, action, actor_id, actor_name, details)
  values(
    'profiles', p_user_id::text, 'profile_update', auth.uid(), coalesce(v_actor_name,'관리자'),
    jsonb_build_object('display_name', p_display_name, 'role', p_role)
  );
end;
$$;

grant execute on function public.facility_ops_admin_update_profile(uuid,text,text) to authenticated;

-- 8) 변경 이력 자동 기록
create or replace function public.facility_ops_audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_action text;
  v_record_id text;
  v_actor uuid := auth.uid();
  v_actor_name text := '';
  v_old jsonb;
  v_new jsonb;
begin
  if tg_op = 'INSERT' then
    v_action := 'create';
    v_record_id := new.id::text;
    v_new := to_jsonb(new);
  elsif tg_op = 'UPDATE' then
    v_record_id := new.id::text;
    v_old := to_jsonb(old);
    v_new := to_jsonb(new);

    if old.deleted_at is null and new.deleted_at is not null then
      v_action := 'delete';
    elsif old.deleted_at is not null and new.deleted_at is null then
      v_action := 'restore';
    else
      v_action := 'update';
    end if;
  else
    return coalesce(new, old);
  end if;

  if v_actor is not null then
    select coalesce(p.display_name, split_part(coalesce(u.email,''),'@',1), '')
      into v_actor_name
    from auth.users u
    left join public.profiles p on p.id = u.id
    where u.id = v_actor;
  end if;

  insert into public.audit_logs(table_name, record_id, action, actor_id, actor_name, details)
  values(
    tg_table_name,
    v_record_id,
    v_action,
    v_actor,
    coalesce(v_actor_name,''),
    case when tg_op = 'INSERT'
      then jsonb_build_object('new', v_new)
      else jsonb_build_object('old', v_old, 'new', v_new)
    end
  );

  return new;
end;
$$;

drop trigger if exists facilities_audit_v04 on public.facilities;
create trigger facilities_audit_v04 after insert or update on public.facilities
for each row execute function public.facility_ops_audit_row();

drop trigger if exists inspections_audit_v04 on public.inspections;
create trigger inspections_audit_v04 after insert or update on public.inspections
for each row execute function public.facility_ops_audit_row();

drop trigger if exists issues_audit_v04 on public.issues;
create trigger issues_audit_v04 after insert or update on public.issues
