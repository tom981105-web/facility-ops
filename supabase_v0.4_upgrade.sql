grant select on public.audit_logs to authenticated;

-- 13) 일반 화면에는 휴지통 데이터가 보이지 않도록 읽기 정책 교체
--     등록/수정은 member/admin, 직접 DELETE는 불가.
do $$
declare
  t text;
begin
  foreach t in array array['facilities','inspections','issues','schedules'] loop
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_write', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert_v04', t);
    execute format('drop policy if exists %I on public.%I', t || '_update_v04', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete_v04', t);

    execute format(
      'create policy %I on public.%I for select to authenticated using (deleted_at is null)',
      t || '_read', t
    );
    execute format(
      'create policy %I on public.%I for insert to authenticated with check (public.facility_ops_can_edit() and deleted_at is null)',
      t || '_insert_v04', t
    );
    execute format(
      'create policy %I on public.%I for update to authenticated using (public.facility_ops_can_edit() and deleted_at is null) with check (public.facility_ops_can_edit() and deleted_at is null)',
      t || '_update_v04', t
    );
  end loop;
end $$;

-- hard delete는 권한 자체도 제거. 삭제는 facility_ops_soft_delete RPC만 사용.
