-- 9) 삭제는 본인 또는 관리자만 가능. 실제 행 삭제 대신 휴지통 처리.
create or replace function public.facility_ops_soft_delete(p_table text, p_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_owner uuid;
  v_deleted_at timestamptz;
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception '로그인이 필요합니다.';
  end if;

  if p_table not in ('facilities','inspections','issues','schedules') then
    raise exception '허용되지 않은 데이터 종류입니다.';
  end if;

  execute format('select created_by, deleted_at from public.%I where id = $1', p_table)
    into v_owner, v_deleted_at using p_id;

  if not found then
    raise exception '항목을 찾을 수 없습니다.';
  end if;

  if v_deleted_at is not null then
    return;
  end if;

  if not public.facility_ops_is_admin() and v_owner is distinct from v_uid then
    raise exception '본인이 등록한 항목만 삭제할 수 있습니다.' using errcode = '42501';
  end if;

  execute format('update public.%I set deleted_at = now(), deleted_by = $1 where id = $2', p_table)
    using v_uid, p_id;
end;
$$;

grant execute on function public.facility_ops_soft_delete(text,text) to authenticated;

-- 10) 휴지통 목록 / 복원은 관리자만
create or replace function public.facility_ops_admin_list_trash()
returns table (
  table_name text,
  record_id text,
  title text,
  deleted_at timestamptz,
  deleted_by uuid,
  created_by uuid
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자만 휴지통을 볼 수 있습니다.' using errcode = '42501';
  end if;

  return query
    select 'facilities'::text, f.id::text, f.name::text, f.deleted_at, f.deleted_by, f.created_by
    from public.facilities f where f.deleted_at is not null
  union all
    select 'inspections'::text, i.id::text,
           ('점검 · ' || coalesce(i.date::text,''))::text, i.deleted_at, i.deleted_by, i.created_by
    from public.inspections i where i.deleted_at is not null
  union all
    select 'issues'::text, q.id::text, q.title::text, q.deleted_at, q.deleted_by, q.created_by
    from public.issues q where q.deleted_at is not null
  union all
    select 'schedules'::text, s.id::text, s.title::text, s.deleted_at, s.deleted_by, s.created_by
    from public.schedules s where s.deleted_at is not null
  order by deleted_at desc;
end;
$$;

grant execute on function public.facility_ops_admin_list_trash() to authenticated;

create or replace function public.facility_ops_admin_restore_record(p_table text, p_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자만 휴지통 항목을 복원할 수 있습니다.' using errcode = '42501';
  end if;

  if p_table not in ('facilities','inspections','issues','schedules') then
    raise exception '허용되지 않은 데이터 종류입니다.';
  end if;

  execute format('update public.%I set deleted_at = null, deleted_by = null where id = $1', p_table)
    using p_id;
end;
$$;

grant execute on function public.facility_ops_admin_restore_record(text,text) to authenticated;

