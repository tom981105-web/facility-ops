      and p.role = 'admin'
  );
$$;

create or replace function public.facility_ops_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.facility_ops_has_admin_role()
     and coalesce(auth.jwt()->>'aal','aal1') = 'aal2';
$$;

create or replace function public.facility_ops_can_edit()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.approved = true
      and p.account_status = 'active'
      and (
        p.role = 'member'
        or (p.role = 'admin' and coalesce(auth.jwt()->>'aal','aal1') = 'aal2')
      )
  );
$$;

