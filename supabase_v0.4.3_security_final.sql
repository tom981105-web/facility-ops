create or replace function public.facility_ops_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.approved = true
      and p.account_status = 'active'
  );
$$;

create or replace function public.facility_ops_is_approved()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.facility_ops_is_active();
$$;

create or replace function public.facility_ops_has_admin_role()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.approved = true
