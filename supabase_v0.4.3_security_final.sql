create or replace function public.facility_ops_admin_list_users_v043()
returns table (
  id uuid,
  login_id text,
  display_name text,
  role text,
  approved boolean,
  account_status text,
  last_seen timestamptz,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자 2단계 인증이 필요합니다.' using errcode = '42501';
  end if;

  return query
  select
    u.id,
    split_part(coalesce(u.email,''), '@', 1) as login_id,
    coalesce(p.display_name, split_part(coalesce(u.email,''), '@', 1)) as display_name,
    coalesce(p.role, 'member') as role,
    coalesce(p.approved, false) as approved,
    coalesce(p.account_status, case when coalesce(p.approved,false) then 'active' else 'pending' end) as account_status,
    p.last_seen,
    u.created_at
  from auth.users u
  left join public.profiles p on p.id = u.id
  order by coalesce(p.display_name, split_part(coalesce(u.email,''), '@', 1));
end;
$$;

create or replace function public.facility_ops_admin_update_profile_v043(
  p_user_id uuid,
  p_display_name text,
  p_role text,
  p_account_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_name text;
  v_old_status text;
begin
  if not public.facility_ops_is_admin() then
    raise exception '관리자 2단계 인증이 필요합니다.' using errcode = '42501';
  end if;

  if p_role not in ('admin','member','viewer') then
    raise exception '올바르지 않은 권한입니다.';
  end if;

  if p_account_status not in ('pending','active','suspended','disabled') then
    raise exception '올바르지 않은 계정 상태입니다.';
  end if;

  if char_length(coalesce(trim(p_display_name),'')) > 80 then
    raise exception '표시 이름은 80자 이하여야 합니다.';
  end if;

  if p_user_id = auth.uid()
     and (p_role <> 'admin' or p_account_status <> 'active') then
    raise exception '현재 관리자 자신의 관리자 권한 또는 활성 상태는 해제할 수 없습니다.';
  end if;

  select p.account_status into v_old_status
  from public.profiles p
  where p.id = p_user_id;

  update public.profiles
  set display_name = nullif(trim(p_display_name), ''),
      role = p_role,
      account_status = p_account_status,
      approved = (p_account_status = 'active'),
      updated_at = now()
  where id = p_user_id;

  if not found then
    raise exception '사용자 프로필을 찾을 수 없습니다.';
  end if;

  select coalesce(display_name, '관리자') into v_actor_name
  from public.profiles where id = auth.uid();

  insert into public.audit_logs(table_name, record_id, action, actor_id, actor_name, details)
  values(
    'profiles',
    p_user_id::text,
    'profile_update',
    auth.uid(),
    coalesce(v_actor_name,'관리자'),
    jsonb_build_object(
      'display_name', p_display_name,
      'role', p_role,
      'account_status', p_account_status
    )
  );

  if coalesce(v_old_status,'pending') is distinct from p_account_status then
    insert into public.security_events(actor_id, actor_name, event_type, details)
    values(
      auth.uid(),
      coalesce(v_actor_name,'관리자'),
      'account_status_change',
      jsonb_build_object(
        'target_user_id', p_user_id,
        'before', coalesce(v_old_status,'pending'),
        'after', p_account_status
      )
    );
  end if;
end;
$$;

create or replace function public.facility_ops_log_security_event(
  p_event_type text,
  p_details jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := '';
  v_event text := trim(coalesce(p_event_type,''));
  v_details jsonb := coalesce(p_details,'{}'::jsonb);
begin
  if auth.uid() is null or not public.facility_ops_is_active() then
    raise exception '활성 로그인 계정이 필요합니다.' using errcode = '42501';
  end if;

  if v_event not in (
    'login_success',
    'logout',
    'idle_logout',
    'admin_center_open',
    'backup_export',
    'backup_import',
    'security_test',
    'security_events_view',
    'mfa_verified'
  ) then
    raise exception '허용되지 않은 보안 이벤트입니다.';
  end if;

  if octet_length(v_details::text) > 4096 then
    raise exception '보안 이벤트 상세 정보가 너무 큽니다.';
  end if;

  select coalesce(p.display_name, split_part(coalesce(u.email,''),'@',1), '')
    into v_name
  from auth.users u
  left join public.profiles p on p.id = u.id
  where u.id = auth.uid();

  insert into public.security_events(actor_id, actor_name, event_type, details)
  values(auth.uid(), coalesce(v_name,''), v_event, v_details);
end;
$$;

